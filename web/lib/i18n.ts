export function useT() {
  const lang = useLangStore((s) => s.lang);
  // One-time, post-mount language detection (see note above). The module guard
  // means only the first mounted component does the work; the store update then
  // re-renders every subscriber.
  useEffect(() => {
    if (_langInited) return;
    _langInited = true;
    const detected = detectInitial();
    document.documentElement.setAttribute('lang', detected === 'zh' ? 'zh-CN' : 'en');
    if (detected !== useLangStore.getState().lang) useLangStore.setState({ lang: detected });
  }, []);
  return (key: string, vars?: Record<string, string | number>): string => {
    let s = DICT[lang][key] ?? DICT.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  };
}
